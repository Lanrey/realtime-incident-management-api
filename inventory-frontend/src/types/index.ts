export interface Product {
  id: string;
  sku: string;
  name: string;
  description?: string;
  reorderThreshold: number;
  reorderQuantity: number;
  leadTimeDays: number;
  unitPrice: number;
  isActive: boolean;
  defaultSupplierId: string;
  defaultSupplier?: Supplier;
  createdAt: string;
  updatedAt: string;
}

export interface ProductStock {
  id: string;
  productId: string;
  warehouseId: string;
  quantity: number;
  lastUpdated: string;
  product?: Product;
  warehouse?: Warehouse;
}

export interface Warehouse {
  id: string;
  name: string;
  location: string;
  capacity: number;
  currentStock: number;
  isActive: boolean;
  utilizationPercentage?: number;
  createdAt: string;
  updatedAt: string;
}

export interface Supplier {
  id: string;
  name: string;
  contactEmail: string;
  contactPhone: string;
  address?: string;
  isActive: boolean;
  createdAt: string;
  updatedAt: string;
}

export interface PurchaseOrder {
  id: string;
  orderNumber: string;
  productId: string;
  supplierId: string;
  warehouseId: string;
  quantityOrdered: number;
  totalCost: number;
  status: 'PENDING' | 'IN_TRANSIT' | 'ARRIVED' | 'CANCELLED';
  orderDate: string;
  expectedArrivalDate: string;
  actualArrivalDate?: string;
  notes?: string;
  isAutoGenerated: boolean;
  product?: Product;
  supplier?: Supplier;
  warehouse?: Warehouse;
  createdAt: string;
  updatedAt: string;
}

export interface ApiResponse<T> {
  success: boolean;
  data?: T;
  error?: {
    message: string;
    code?: string;
    details?: any;
  };
  meta?: {
    page: number;
    limit: number;
    total: number;
    totalPages: number;
  };
}

export interface DashboardStats {
  products: {
    total: number;
    lowStock: number;
  };
  warehouses: {
    total: number;
    avgUtilization: number;
  };
  orders: {
    pending: number;
    inTransit: number;
    totalValue: number;
  };
}
