import { useEffect, useRef, useCallback } from 'react';
import toast from 'react-hot-toast';

interface SSEEvent {
  stock?: {
    productId: string;
    warehouseId: string;
    quantity: number;
    productName?: string;
    warehouseName?: string;
  };
  alert?: {
    id: string;
    type: string;
    severity: string;
    message: string;
    metadata?: any;
    resolved?: boolean;
  };
  order?: {
    id: string;
    orderNumber: string;
    productId: string;
    warehouseId: string;
    status: string;
    isAutoGenerated: boolean;
  };
  warehouse?: {
    id: string;
    name: string;
    currentStock: number;
    capacity: number;
    percentage: number;
  };
}

const playNotificationSound = () => {
  try {
    const audio = new Audio('/notification.mp3');
    audio.volume = 0.5;
    audio.play().catch((error) => {
      console.warn('Could not play notification sound:', error);
    });
  } catch (error) {
    console.warn('Audio not supported:', error);
  }
};

const getToastIcon = (severity?: string, type?: string) => {
  if (severity === 'CRITICAL' || severity === 'ERROR') return '🔴';
  if (severity === 'WARNING') return '⚠️';
  if (type === 'stock') return '📦';
  if (type === 'order') return '🛒';
  if (type === 'warehouse') return '🏭';
  return '🔔';
};

export const useSSE = (onEvent?: (eventType: string, data: any) => void) => {
  const eventSourceRef = useRef<EventSource | null>(null);
  const reconnectTimeoutRef = useRef<NodeJS.Timeout>();
  const reconnectAttempts = useRef(0);
  const maxReconnectAttempts = 10;

  const showNotification = useCallback((eventType: string, data: any) => {
    playNotificationSound();

    switch (eventType) {
      case 'stock':
        toast.success(
          `Stock Updated: ${data.productName || 'Product'} - ${data.quantity} units${
            data.warehouseName ? ` in ${data.warehouseName}` : ''
          }`,
          {
            icon: '📦',
            duration: 5000,
          }
        );
        break;

      case 'alert':
        if (data.resolved) {
          toast.success(`Alert Resolved: ${data.type}`, {
            icon: '✅',
            duration: 4000,
          });
        } else {
          const toastFn =
            data.severity === 'CRITICAL' || data.severity === 'ERROR'
              ? toast.error
              : data.severity === 'WARNING'
              ? toast
              : toast.success;

          toastFn(data.message, {
            icon: getToastIcon(data.severity),
            duration: data.severity === 'CRITICAL' ? 10000 : 6000,
            style:
              data.severity === 'CRITICAL'
                ? {
                    border: '2px solid #ef4444',
                    padding: '16px',
                    fontWeight: 'bold',
                  }
                : undefined,
          });
        }
        break;

      case 'order':
        const statusEmoji = {
          PENDING: '⏳',
          IN_TRANSIT: '🚚',
          ARRIVED: '✅',
          CANCELLED: '❌',
        }[data.status] || '📋';

        toast(
          `${data.isAutoGenerated ? 'Auto-generated' : 'Manual'} Order ${
            data.status === 'ARRIVED' ? 'Arrived' : 'Updated'
          }: ${data.orderNumber}`,
          {
            icon: statusEmoji,
            duration: 5000,
          }
        );
        break;

      case 'warehouse':
        const capacityPercentage = Math.round(data.percentage);
        const capacityIcon = capacityPercentage >= 90 ? '🔴' : capacityPercentage >= 80 ? '⚠️' : '🏭';

        toast(
          `Warehouse Update: ${data.name} - ${capacityPercentage}% capacity (${data.currentStock}/${data.capacity})`,
          {
            icon: capacityIcon,
            duration: 5000,
            style:
              capacityPercentage >= 90
                ? {
                    border: '2px solid #ef4444',
                  }
                : undefined,
          }
        );
        break;

      default:
        toast.info(`Event: ${eventType}`, {
          icon: '🔔',
          duration: 4000,
        });
    }
  }, []);

  const connect = useCallback(() => {
    if (eventSourceRef.current?.readyState === EventSource.OPEN) {
      return;
    }

    try {
      const apiUrl = import.meta.env.VITE_API_URL || 'http://localhost:3000';
      const eventSource = new EventSource(`${apiUrl}/api/events`);

      eventSource.onopen = () => {
        console.log('✅ SSE Connected');
        reconnectAttempts.current = 0;
      };

      eventSource.addEventListener('connected', (event) => {
        const data = JSON.parse(event.data);
        console.log('🔗 SSE Connection established:', data.clientId);
      });

      eventSource.addEventListener('stock', (event) => {
        const data = JSON.parse(event.data);
        console.log('📦 Stock update:', data);
        showNotification('stock', data);
        onEvent?.('stock', data);
      });

      eventSource.addEventListener('alert', (event) => {
        const data = JSON.parse(event.data);
        console.log('🔔 Alert:', data);
        showNotification('alert', data);
        onEvent?.('alert', data);
      });

      eventSource.addEventListener('order', (event) => {
        const data = JSON.parse(event.data);
        console.log('🛒 Order update:', data);
        showNotification('order', data);
        onEvent?.('order', data);
      });

      eventSource.addEventListener('warehouse', (event) => {
        const data = JSON.parse(event.data);
        console.log('🏭 Warehouse update:', data);
        showNotification('warehouse', data);
        onEvent?.('warehouse', data);
      });

      eventSource.onerror = (error) => {
        console.error('❌ SSE Error:', error);
        eventSource.close();

        // Implement exponential backoff for reconnection
        if (reconnectAttempts.current < maxReconnectAttempts) {
          const delay = Math.min(1000 * Math.pow(2, reconnectAttempts.current), 30000);
          console.log(`🔄 Reconnecting in ${delay}ms...`);

          reconnectTimeoutRef.current = setTimeout(() => {
            reconnectAttempts.current++;
            connect();
          }, delay);
        } else {
          toast.error('Lost connection to server. Please refresh the page.', {
            duration: Infinity,
            icon: '❌',
          });
        }
      };

      eventSourceRef.current = eventSource;
    } catch (error) {
      console.error('Failed to create EventSource:', error);
    }
  }, [onEvent, showNotification]);

  const disconnect = useCallback(() => {
    if (reconnectTimeoutRef.current) {
      clearTimeout(reconnectTimeoutRef.current);
    }
    if (eventSourceRef.current) {
      eventSourceRef.current.close();
      eventSourceRef.current = null;
      console.log('🔌 SSE Disconnected');
    }
  }, []);

  useEffect(() => {
    connect();

    return () => {
      disconnect();
    };
  }, [connect, disconnect]);

  return {
    connected: eventSourceRef.current?.readyState === EventSource.OPEN,
    disconnect,
    reconnect: connect,
  };
};
