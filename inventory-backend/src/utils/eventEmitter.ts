import { EventEmitter } from 'events';
import { logger } from './logger';

/**
 * Application Event Emitter
 *
 * Central event bus for internal application events.
 * Used for broadcasting real-time updates via SSE.
 *
 * Events:
 * - stock:update - Stock level changed
 * - alert:new - New alert created
 * - alert:resolved - Alert resolved
 * - order:created - Purchase order created
 * - order:updated - Purchase order status changed
 * - warehouse:updated - Warehouse capacity changed
 */

class AppEventEmitter extends EventEmitter {
  constructor() {
    super();
    this.setMaxListeners(100); // Support multiple SSE clients
  }

  /**
   * Emit stock update event
   */
  emitStockUpdate(data: {
    productId: string;
    warehouseId: string;
    quantity: number;
    productName?: string;
    warehouseName?: string;
  }) {
    logger.debug({ data }, 'Emitting stock:update event');
    this.emit('stock:update', data);
  }

  /**
   * Emit new alert event
   */
  emitAlertNew(data: {
    id: string;
    type: string;
    severity: string;
    message: string;
    metadata?: any;
  }) {
    logger.debug({ data }, 'Emitting alert:new event');
    this.emit('alert:new', data);
  }

  /**
   * Emit alert resolved event
   */
  emitAlertResolved(data: {
    id: string;
    type: string;
  }) {
    logger.debug({ data }, 'Emitting alert:resolved event');
    this.emit('alert:resolved', data);
  }

  /**
   * Emit purchase order created event
   */
  emitOrderCreated(data: {
    id: string;
    orderNumber: string;
    productId: string;
    warehouseId: string;
    status: string;
    isAutoGenerated: boolean;
  }) {
    logger.debug({ data }, 'Emitting order:created event');
    this.emit('order:created', data);
  }

  /**
   * Emit purchase order updated event
   */
  emitOrderUpdated(data: {
    id: string;
    orderNumber: string;
    status: string;
  }) {
    logger.debug({ data }, 'Emitting order:updated event');
    this.emit('order:updated', data);
  }

  /**
   * Emit warehouse capacity updated event
   */
  emitWarehouseUpdated(data: {
    id: string;
    name: string;
    currentStock: number;
    capacity: number;
    percentage: number;
  }) {
    logger.debug({ data }, 'Emitting warehouse:updated event');
    this.emit('warehouse:updated', data);
  }
}

// Singleton instance
export const appEvents = new AppEventEmitter();
