import Joi from 'joi';

export const createPurchaseOrderSchema = Joi.object({
  productId: Joi.string().uuid().required(),
  supplierId: Joi.string().uuid().required(),
  warehouseId: Joi.string().uuid().required(),
  quantityOrdered: Joi.number().integer().min(1).required(),
  notes: Joi.string().optional(),
});

export const updatePurchaseOrderSchema = Joi.object({
  status: Joi.string().valid('PENDING', 'IN_TRANSIT', 'ARRIVED', 'CANCELLED').optional(),
  notes: Joi.string().optional(),
});

export const queryPurchaseOrdersSchema = Joi.object({
  page: Joi.number().integer().min(1).default(1),
  limit: Joi.number().integer().min(1).max(100).default(20),
  status: Joi.string().valid('PENDING', 'IN_TRANSIT', 'ARRIVED', 'CANCELLED').optional(),
  warehouseId: Joi.string().uuid().optional(),
  productId: Joi.string().uuid().optional(),
  supplierId: Joi.string().uuid().optional(),
  isAutoGenerated: Joi.boolean().optional(),
  startDate: Joi.string().optional(),
  endDate: Joi.string().optional(),
  sortBy: Joi.string().valid('orderDate', 'expectedArrivalDate', 'orderNumber').default('orderDate'),
  sortOrder: Joi.string().valid('asc', 'desc').default('desc'),
});

export interface CreatePurchaseOrderInput {
  productId: string;
  supplierId: string;
  warehouseId: string;
  quantityOrdered: number;
  notes?: string;
}

export interface UpdatePurchaseOrderInput {
  status?: 'PENDING' | 'IN_TRANSIT' | 'ARRIVED' | 'CANCELLED';
  notes?: string;
}

export interface QueryPurchaseOrdersInput {
  page?: number;
  limit?: number;
  status?: 'PENDING' | 'IN_TRANSIT' | 'ARRIVED' | 'CANCELLED';
  warehouseId?: string;
  productId?: string;
  supplierId?: string;
  isAutoGenerated?: boolean;
  startDate?: string;
  endDate?: string;
  sortBy?: 'orderDate' | 'expectedArrivalDate' | 'orderNumber';
  sortOrder?: 'asc' | 'desc';
}
