import { prisma } from '../config/database';
import { rabbitmq } from '../config/rabbitmq';
import { logger } from '../utils/logger';
import { capacityManager } from './capacityManager.service';
import { appEvents } from '../utils/eventEmitter';
import { Prisma } from '@prisma/client';
import type {
  CreatePurchaseOrderInput,
  UpdatePurchaseOrderInput,
  QueryPurchaseOrdersInput,
} from '../schemas/purchaseOrder.schema';

export class PurchaseOrderService {
  async createPurchaseOrder(data: CreatePurchaseOrderInput) {
    // Validate warehouse capacity
    const product = await prisma.product.findUnique({
      where: { id: data.productId },
    });

    if (!product) {
      throw new Error('Product not found');
    }

    const optimalQuantity = await capacityManager.calculateOptimalOrderQuantity(
      data.productId,
      data.warehouseId,
      data.quantityOrdered
    );

    if (optimalQuantity <= 0) {
      throw new Error('Warehouse has insufficient capacity for this order');
    }

    if (optimalQuantity < data.quantityOrdered) {
      logger.warn(
        { requested: data.quantityOrdered, adjusted: optimalQuantity },
        'Order quantity adjusted due to capacity constraints'
      );
    }

    // Calculate dates
    const orderDate = new Date();
    const expectedArrivalDate = new Date(orderDate);
    expectedArrivalDate.setDate(
      expectedArrivalDate.getDate() + product.leadTimeDays
    );

    // Create order with retry logic for unique constraint
    let order;
    let retries = 3;
    let success = false;

    while (retries > 0 && !success) {
      try {
        const orderNumber = await this.generateOrderNumber();

        order = await prisma.purchaseOrder.create({
          data: {
            orderNumber,
            productId: data.productId,
            supplierId: data.supplierId,
            warehouseId: data.warehouseId,
            quantityOrdered: optimalQuantity,
            totalCost: product.unitPrice * optimalQuantity,
            status: 'PENDING',
            orderDate,
            expectedArrivalDate,
            notes: data.notes,
            isAutoGenerated: false,
          },
          include: {
            product: true,
            supplier: true,
            warehouse: true,
          },
        });

        success = true;
        logger.info({ orderId: order.id, orderNumber: order.orderNumber }, 'Purchase order created');

        // Emit SSE event for real-time notification
        appEvents.emitOrderCreated({
          id: order.id,
          orderNumber: order.orderNumber,
          productId: order.productId,
          warehouseId: order.warehouseId,
          status: order.status,
          isAutoGenerated: order.isAutoGenerated,
        });
      } catch (error: any) {
        if (error.code === 'P2002' && retries > 1) {
          // Unique constraint violation - retry with new order number
          retries--;
          logger.warn({ retries }, 'Order number collision, retrying...');
          await new Promise(resolve => setTimeout(resolve, 100));
        } else {
          throw error;
        }
      }
    }

    return order!;
  }

  async getPurchaseOrders(query: QueryPurchaseOrdersInput) {
    const {
      page,
      limit,
      status,
      warehouseId,
      productId,
      supplierId,
      isAutoGenerated,
      startDate,
      endDate,
      sortBy,
      sortOrder,
    } = query;

    const skip = (page - 1) * limit;

    const where: Prisma.PurchaseOrderWhereInput = {
      ...(status && { status }),
      ...(warehouseId && { warehouseId }),
      ...(productId && { productId }),
      ...(supplierId && { supplierId }),
      ...(isAutoGenerated !== undefined && { isAutoGenerated }),
      ...(startDate &&
        endDate && {
          orderDate: {
            gte: new Date(startDate),
            lte: new Date(endDate),
          },
        }),
    };

    const [orders, total] = await Promise.all([
      prisma.purchaseOrder.findMany({
        where,
        skip,
        take: limit,
        orderBy: { [sortBy]: sortOrder },
        include: {
          product: {
            select: {
              id: true,
              sku: true,
              name: true,
            },
          },
          supplier: {
            select: {
              id: true,
              name: true,
              contactEmail: true,
            },
          },
          warehouse: {
            select: {
              id: true,
              name: true,
              location: true,
            },
          },
        },
      }),
      prisma.purchaseOrder.count({ where }),
    ]);

    return {
      orders,
      pagination: {
        page,
        limit,
        total,
        totalPages: Math.ceil(total / limit),
      },
    };
  }

  async getPurchaseOrderById(id: string) {
    const order = await prisma.purchaseOrder.findUnique({
      where: { id },
      include: {
        product: true,
        supplier: true,
        warehouse: true,
      },
    });

    return order;
  }

  async updatePurchaseOrder(id: string, data: UpdatePurchaseOrderInput) {
    const order = await prisma.purchaseOrder.update({
      where: { id },
      data,
      include: {
        product: true,
        supplier: true,
        warehouse: true,
      },
    });

    logger.info({ orderId: id }, 'Purchase order updated');

    // Emit SSE event for real-time notification if status changed
    if (data.status) {
      appEvents.emitOrderUpdated({
        id: order.id,
        orderNumber: order.orderNumber,
        status: order.status,
      });
    }

    return order;
  }

  async markOrderAsArrived(id: string) {
    // Publish to queue for async processing
    await rabbitmq.publish(
      'order.arrival',
      {
        purchaseOrderId: id,
      },
      8 // High priority
    );

    logger.info({ orderId: id }, 'Order arrival processing initiated');
    return { message: 'Order arrival is being processed' };
  }

  async cancelPurchaseOrder(id: string) {
    const order = await prisma.purchaseOrder.findUnique({
      where: { id },
    });

    if (!order) {
      throw new Error('Purchase order not found');
    }

    if (order.status === 'ARRIVED') {
      throw new Error('Cannot cancel an order that has already arrived');
    }

    await prisma.purchaseOrder.update({
      where: { id },
      data: {
        status: 'CANCELLED',
      },
    });

    logger.info({ orderId: id }, 'Purchase order cancelled');
  }

  async getPendingOrders(warehouseId?: string) {
    const where: Prisma.PurchaseOrderWhereInput = {
      status: {
        in: ['PENDING', 'IN_TRANSIT'],
      },
      ...(warehouseId && { warehouseId }),
    };

    const orders = await prisma.purchaseOrder.findMany({
      where,
      orderBy: { expectedArrivalDate: 'asc' },
      include: {
        product: {
          select: {
            id: true,
            sku: true,
            name: true,
          },
        },
        supplier: {
          select: {
            id: true,
            name: true,
          },
        },
        warehouse: {
          select: {
            id: true,
            name: true,
          },
        },
      },
    });

    return orders;
  }

  async getOrderStatistics(warehouseId?: string) {
    const where: Prisma.PurchaseOrderWhereInput = {
      ...(warehouseId && { warehouseId }),
    };

    const [totalOrders, pendingOrders, inTransitOrders, arrivedOrders, totalValue] =
      await Promise.all([
        prisma.purchaseOrder.count({ where }),
        prisma.purchaseOrder.count({
          where: { ...where, status: 'PENDING' },
        }),
        prisma.purchaseOrder.count({
          where: { ...where, status: 'IN_TRANSIT' },
        }),
        prisma.purchaseOrder.count({
          where: { ...where, status: 'ARRIVED' },
        }),
        prisma.purchaseOrder.aggregate({
          where: { ...where, status: { not: 'CANCELLED' } },
          _sum: { totalCost: true },
        }),
      ]);

    return {
      totalOrders,
      pendingOrders,
      inTransitOrders,
      arrivedOrders,
      totalValue: totalValue._sum.totalCost || 0,
    };
  }

  private async generateOrderNumber(): Promise<string> {
    const date = new Date();
    const year = date.getFullYear();
    const month = String(date.getMonth() + 1).padStart(2, '0');
    const day = String(date.getDate()).padStart(2, '0');
    const timestamp = Date.now().toString().slice(-6); // Last 6 digits of timestamp

    return `PO-${year}${month}${day}-${timestamp}`;
  }
}

export const purchaseOrderService = new PurchaseOrderService();
