import Fastify from 'fastify';
import { purchaseOrderRoutes } from '../../routes/purchaseOrder.routes';
import { prisma } from '../../config/database';
import { rabbitmq } from '../../config/rabbitmq';
import { capacityManager } from '../../services/capacityManager.service';

jest.mock('../../config/rabbitmq');
jest.mock('../../services/capacityManager.service');

const buildApp = async () => {
  const app = Fastify();
  await app.register(purchaseOrderRoutes, { prefix: '/api/purchase-orders' });
  return app;
};

describe('Purchase Order Routes Integration Tests', () => {
  let app: any;

  beforeEach(async () => {
    app = await buildApp();
    jest.clearAllMocks();
  });

  afterEach(async () => {
    await app.close();
  });

  describe('GET /api/purchase-orders', () => {
    it('should return paginated purchase orders', async () => {
      const mockOrders = [
        {
          id: 'order-1',
          orderNumber: 'PO-001',
          status: 'PENDING',
          product: { id: 'p1', sku: 'SKU001', name: 'Product 1' },
          supplier: { id: 's1', name: 'Supplier 1' },
          warehouse: { id: 'w1', name: 'Warehouse 1' },
        },
      ];

      (prisma.purchaseOrder.findMany as jest.Mock).mockResolvedValue(mockOrders);
      (prisma.purchaseOrder.count as jest.Mock).mockResolvedValue(1);

      const response = await app.inject({
        method: 'GET',
        url: '/api/purchase-orders',
      });

      expect(response.statusCode).toBe(200);
      const data = JSON.parse(response.payload);
      expect(data.data).toHaveLength(1);
      expect(data.meta).toBeDefined();
    });

    it('should filter by status', async () => {
      (prisma.purchaseOrder.findMany as jest.Mock).mockResolvedValue([]);
      (prisma.purchaseOrder.count as jest.Mock).mockResolvedValue(0);

      const response = await app.inject({
        method: 'GET',
        url: '/api/purchase-orders?status=PENDING',
      });

      expect(response.statusCode).toBe(200);
      expect(prisma.purchaseOrder.findMany).toHaveBeenCalledWith(
        expect.objectContaining({
          where: expect.objectContaining({ status: 'PENDING' }),
        })
      );
    });

    it('should filter by warehouse', async () => {
      (prisma.purchaseOrder.findMany as jest.Mock).mockResolvedValue([]);
      (prisma.purchaseOrder.count as jest.Mock).mockResolvedValue(0);

      const response = await app.inject({
        method: 'GET',
        url: '/api/purchase-orders?warehouseId=warehouse-1',
      });

      expect(response.statusCode).toBe(200);
      expect(prisma.purchaseOrder.findMany).toHaveBeenCalledWith(
        expect.objectContaining({
          where: expect.objectContaining({ warehouseId: 'warehouse-1' }),
        })
      );
    });

    it('should filter by date range', async () => {
      (prisma.purchaseOrder.findMany as jest.Mock).mockResolvedValue([]);
      (prisma.purchaseOrder.count as jest.Mock).mockResolvedValue(0);

      const response = await app.inject({
        method: 'GET',
        url: '/api/purchase-orders?startDate=2023-01-01&endDate=2023-12-31',
      });

      expect(response.statusCode).toBe(200);
      expect(prisma.purchaseOrder.findMany).toHaveBeenCalledWith(
        expect.objectContaining({
          where: expect.objectContaining({
            orderDate: {
              gte: new Date('2023-01-01'),
              lte: new Date('2023-12-31'),
            },
          }),
        })
      );
    });

    it('should filter by isAutoGenerated', async () => {
      (prisma.purchaseOrder.findMany as jest.Mock).mockResolvedValue([]);
      (prisma.purchaseOrder.count as jest.Mock).mockResolvedValue(0);

      const response = await app.inject({
        method: 'GET',
        url: '/api/purchase-orders?isAutoGenerated=true',
      });

      expect(response.statusCode).toBe(200);
      expect(prisma.purchaseOrder.findMany).toHaveBeenCalledWith(
        expect.objectContaining({
          where: expect.objectContaining({ isAutoGenerated: true }),
        })
      );
    });

    it('should handle errors gracefully', async () => {
      (prisma.purchaseOrder.findMany as jest.Mock).mockRejectedValue(
        new Error('Database error')
      );

      const response = await app.inject({
        method: 'GET',
        url: '/api/purchase-orders',
      });

      expect(response.statusCode).toBe(500);
    });
  });

  describe('POST /api/purchase-orders', () => {
    const mockProduct = {
      id: 'product-1',
      unitPrice: 100,
      leadTimeDays: 7,
    };

    const mockOrder = {
      id: 'order-1',
      orderNumber: 'PO-20231201-123456',
      productId: 'product-1',
      supplierId: 'supplier-1',
      warehouseId: 'warehouse-1',
      quantityOrdered: 50,
      totalCost: 5000,
      status: 'PENDING',
    };

    it('should create purchase order successfully', async () => {
      (prisma.product.findUnique as jest.Mock).mockResolvedValue(mockProduct);
      (capacityManager.calculateOptimalOrderQuantity as jest.Mock).mockResolvedValue(50);
      (prisma.purchaseOrder.create as jest.Mock).mockResolvedValue(mockOrder);

      const response = await app.inject({
        method: 'POST',
        url: '/api/purchase-orders',
        payload: {
          productId: 'product-1',
          supplierId: 'supplier-1',
          warehouseId: 'warehouse-1',
          quantityOrdered: 50,
          notes: 'Test order',
        },
      });

      expect(response.statusCode).toBe(201);
      const data = JSON.parse(response.payload);
      expect(data.data.quantityOrdered).toBe(50);
    });

    it('should reject order when product not found', async () => {
      (prisma.product.findUnique as jest.Mock).mockResolvedValue(null);

      const response = await app.inject({
        method: 'POST',
        url: '/api/purchase-orders',
        payload: {
          productId: 'non-existent',
          supplierId: 'supplier-1',
          warehouseId: 'warehouse-1',
          quantityOrdered: 50,
        },
      });

      expect(response.statusCode).toBe(400);
    });

    it('should reject order when warehouse has insufficient capacity', async () => {
      (prisma.product.findUnique as jest.Mock).mockResolvedValue(mockProduct);
      (capacityManager.calculateOptimalOrderQuantity as jest.Mock).mockResolvedValue(0);

      const response = await app.inject({
        method: 'POST',
        url: '/api/purchase-orders',
        payload: {
          productId: 'product-1',
          supplierId: 'supplier-1',
          warehouseId: 'warehouse-1',
          quantityOrdered: 1000,
        },
      });

      expect(response.statusCode).toBe(400);
    });

    it('should validate required fields', async () => {
      const response = await app.inject({
        method: 'POST',
        url: '/api/purchase-orders',
        payload: {
          productId: 'product-1',
          // Missing required fields
        },
      });

      expect(response.statusCode).toBe(400);
    });

    it('should validate quantityOrdered is positive', async () => {
      const response = await app.inject({
        method: 'POST',
        url: '/api/purchase-orders',
        payload: {
          productId: 'product-1',
          supplierId: 'supplier-1',
          warehouseId: 'warehouse-1',
          quantityOrdered: -10,
        },
      });

      expect(response.statusCode).toBe(400);
    });

    it('should adjust quantity based on capacity constraints', async () => {
      (prisma.product.findUnique as jest.Mock).mockResolvedValue(mockProduct);
      (capacityManager.calculateOptimalOrderQuantity as jest.Mock).mockResolvedValue(30);
      (prisma.purchaseOrder.create as jest.Mock).mockResolvedValue({
        ...mockOrder,
        quantityOrdered: 30,
      });

      const response = await app.inject({
        method: 'POST',
        url: '/api/purchase-orders',
        payload: {
          productId: 'product-1',
          supplierId: 'supplier-1',
          warehouseId: 'warehouse-1',
          quantityOrdered: 50,
        },
      });

      expect(response.statusCode).toBe(201);
      const data = JSON.parse(response.payload);
      expect(data.data.quantityOrdered).toBe(30);
    });
  });

  describe('GET /api/purchase-orders/:id', () => {
    it('should return purchase order by ID', async () => {
      const mockOrder = {
        id: 'order-1',
        orderNumber: 'PO-001',
        status: 'PENDING',
      };

      (prisma.purchaseOrder.findUnique as jest.Mock).mockResolvedValue(mockOrder);

      const response = await app.inject({
        method: 'GET',
        url: '/api/purchase-orders/order-1',
      });

      expect(response.statusCode).toBe(200);
      const data = JSON.parse(response.payload);
      expect(data.data.id).toBe('order-1');
    });

    it('should return 404 for non-existent order', async () => {
      (prisma.purchaseOrder.findUnique as jest.Mock).mockResolvedValue(null);

      const response = await app.inject({
        method: 'GET',
        url: '/api/purchase-orders/non-existent',
      });

      expect(response.statusCode).toBe(404);
    });
  });

  describe('PUT /api/purchase-orders/:id', () => {
    it('should update purchase order', async () => {
      const mockUpdatedOrder = {
        id: 'order-1',
        status: 'IN_TRANSIT',
      };

      (prisma.purchaseOrder.update as jest.Mock).mockResolvedValue(mockUpdatedOrder);

      const response = await app.inject({
        method: 'PUT',
        url: '/api/purchase-orders/order-1',
        payload: {
          status: 'IN_TRANSIT',
        },
      });

      expect(response.statusCode).toBe(200);
      const data = JSON.parse(response.payload);
      expect(data.data.status).toBe('IN_TRANSIT');
    });

    it('should handle not found error', async () => {
      (prisma.purchaseOrder.update as jest.Mock).mockRejectedValue({
        code: 'P2025',
        message: 'Record not found',
      });

      const response = await app.inject({
        method: 'PUT',
        url: '/api/purchase-orders/non-existent',
        payload: {
          status: 'IN_TRANSIT',
        },
      });

      expect(response.statusCode).toBe(500);
    });
  });

  describe('POST /api/purchase-orders/:id/arrive', () => {
    it('should mark order as arrived via queue', async () => {
      (rabbitmq.publish as jest.Mock).mockResolvedValue(undefined);

      const response = await app.inject({
        method: 'POST',
        url: '/api/purchase-orders/order-1/arrive',
      });

      expect(response.statusCode).toBe(200);
      expect(rabbitmq.publish).toHaveBeenCalledWith(
        'order.arrival',
        { purchaseOrderId: 'order-1' },
        8
      );
    });

    it('should handle queue publish errors', async () => {
      (rabbitmq.publish as jest.Mock).mockRejectedValue(new Error('Queue error'));

      const response = await app.inject({
        method: 'POST',
        url: '/api/purchase-orders/order-1/arrive',
      });

      expect(response.statusCode).toBe(500);
    });
  });

  describe('POST /api/purchase-orders/:id/cancel', () => {
    it('should cancel pending order', async () => {
      (prisma.purchaseOrder.findUnique as jest.Mock).mockResolvedValue({
        id: 'order-1',
        status: 'PENDING',
      });
      (prisma.purchaseOrder.update as jest.Mock).mockResolvedValue({});

      const response = await app.inject({
        method: 'POST',
        url: '/api/purchase-orders/order-1/cancel',
      });

      expect(response.statusCode).toBe(200);
    });

    it('should reject cancellation of arrived order', async () => {
      (prisma.purchaseOrder.findUnique as jest.Mock).mockResolvedValue({
        id: 'order-1',
        status: 'ARRIVED',
      });

      const response = await app.inject({
        method: 'POST',
        url: '/api/purchase-orders/order-1/cancel',
      });

      expect(response.statusCode).toBe(400);
    });

    it('should return 404 for non-existent order', async () => {
      (prisma.purchaseOrder.findUnique as jest.Mock).mockResolvedValue(null);

      const response = await app.inject({
        method: 'POST',
        url: '/api/purchase-orders/non-existent/cancel',
      });

      expect(response.statusCode).toBe(404);
    });
  });

  describe('GET /api/purchase-orders/pending', () => {
    it('should return pending and in-transit orders', async () => {
      const mockOrders = [
        { id: 'order-1', status: 'PENDING' },
        { id: 'order-2', status: 'IN_TRANSIT' },
      ];

      (prisma.purchaseOrder.findMany as jest.Mock).mockResolvedValue(mockOrders);

      const response = await app.inject({
        method: 'GET',
        url: '/api/purchase-orders/pending',
      });

      expect(response.statusCode).toBe(200);
      const data = JSON.parse(response.payload);
      expect(data.data).toHaveLength(2);
    });

    it('should filter pending orders by warehouse', async () => {
      (prisma.purchaseOrder.findMany as jest.Mock).mockResolvedValue([]);

      const response = await app.inject({
        method: 'GET',
        url: '/api/purchase-orders/pending?warehouseId=warehouse-1',
      });

      expect(response.statusCode).toBe(200);
      expect(prisma.purchaseOrder.findMany).toHaveBeenCalledWith(
        expect.objectContaining({
          where: expect.objectContaining({
            warehouseId: 'warehouse-1',
          }),
        })
      );
    });
  });

  describe('GET /api/purchase-orders/statistics', () => {
    it('should return comprehensive statistics', async () => {
      (prisma.purchaseOrder.count as jest.Mock)
        .mockResolvedValueOnce(100)
        .mockResolvedValueOnce(30)
        .mockResolvedValueOnce(20)
        .mockResolvedValueOnce(45);

      (prisma.purchaseOrder.aggregate as jest.Mock).mockResolvedValue({
        _sum: { totalCost: 50000 },
      });

      const response = await app.inject({
        method: 'GET',
        url: '/api/purchase-orders/statistics',
      });

      expect(response.statusCode).toBe(200);
      const data = JSON.parse(response.payload);
      expect(data.data).toEqual({
        totalOrders: 100,
        pendingOrders: 30,
        inTransitOrders: 20,
        arrivedOrders: 45,
        totalValue: 50000,
      });
    });

    it('should filter statistics by warehouse', async () => {
      (prisma.purchaseOrder.count as jest.Mock).mockResolvedValue(0);
      (prisma.purchaseOrder.aggregate as jest.Mock).mockResolvedValue({
        _sum: { totalCost: null },
      });

      const response = await app.inject({
        method: 'GET',
        url: '/api/purchase-orders/statistics?warehouseId=warehouse-1',
      });

      expect(response.statusCode).toBe(200);
    });
  });

  describe('Edge Cases', () => {
    it('should handle very large order quantities', async () => {
      const mockProduct = {
        id: 'product-1',
        unitPrice: 100,
        leadTimeDays: 7,
      };

      (prisma.product.findUnique as jest.Mock).mockResolvedValue(mockProduct);
      (capacityManager.calculateOptimalOrderQuantity as jest.Mock).mockResolvedValue(
        100000
      );
      (prisma.purchaseOrder.create as jest.Mock).mockResolvedValue({
        id: 'order-1',
        quantityOrdered: 100000,
        totalCost: 10000000,
      });

      const response = await app.inject({
        method: 'POST',
        url: '/api/purchase-orders',
        payload: {
          productId: 'product-1',
          supplierId: 'supplier-1',
          warehouseId: 'warehouse-1',
          quantityOrdered: 100000,
        },
      });

      expect(response.statusCode).toBe(201);
    });

    it('should handle concurrent order cancellations', async () => {
      (prisma.purchaseOrder.findUnique as jest.Mock).mockResolvedValue({
        id: 'order-1',
        status: 'PENDING',
      });
      (prisma.purchaseOrder.update as jest.Mock).mockResolvedValue({});

      const requests = [
        app.inject({
          method: 'POST',
          url: '/api/purchase-orders/order-1/cancel',
        }),
        app.inject({
          method: 'POST',
          url: '/api/purchase-orders/order-1/cancel',
        }),
      ];

      const responses = await Promise.all(requests);

      responses.forEach((response) => {
        expect(response.statusCode).toBeLessThan(500);
      });
    });

    it('should handle orders with very long notes', async () => {
      const longNotes = 'A'.repeat(5000);
      const mockProduct = {
        id: 'product-1',
        unitPrice: 100,
        leadTimeDays: 7,
      };

      (prisma.product.findUnique as jest.Mock).mockResolvedValue(mockProduct);
      (capacityManager.calculateOptimalOrderQuantity as jest.Mock).mockResolvedValue(50);
      (prisma.purchaseOrder.create as jest.Mock).mockResolvedValue({
        id: 'order-1',
        notes: longNotes,
      });

      const response = await app.inject({
        method: 'POST',
        url: '/api/purchase-orders',
        payload: {
          productId: 'product-1',
          supplierId: 'supplier-1',
          warehouseId: 'warehouse-1',
          quantityOrdered: 50,
          notes: longNotes,
        },
      });

      expect(response.statusCode).toBeLessThan(500);
    });

    it('should handle invalid date formats in date range filter', async () => {
      (prisma.purchaseOrder.findMany as jest.Mock).mockResolvedValue([]);
      (prisma.purchaseOrder.count as jest.Mock).mockResolvedValue(0);

      const response = await app.inject({
        method: 'GET',
        url: '/api/purchase-orders?startDate=invalid&endDate=invalid',
      });

      // Should handle gracefully or return 400
      expect(response.statusCode).toBeLessThan(500);
    });

    it('should handle order number collision retry mechanism', async () => {
      const mockProduct = {
        id: 'product-1',
        unitPrice: 100,
        leadTimeDays: 7,
      };

      (prisma.product.findUnique as jest.Mock).mockResolvedValue(mockProduct);
      (capacityManager.calculateOptimalOrderQuantity as jest.Mock).mockResolvedValue(50);
      (prisma.purchaseOrder.create as jest.Mock)
        .mockRejectedValueOnce({ code: 'P2002' })
        .mockRejectedValueOnce({ code: 'P2002' })
        .mockResolvedValueOnce({
          id: 'order-1',
          orderNumber: 'PO-20231201-123456',
        });

      const response = await app.inject({
        method: 'POST',
        url: '/api/purchase-orders',
        payload: {
          productId: 'product-1',
          supplierId: 'supplier-1',
          warehouseId: 'warehouse-1',
          quantityOrdered: 50,
        },
      });

      expect(response.statusCode).toBe(201);
      expect(prisma.purchaseOrder.create).toHaveBeenCalledTimes(3);
    });
  });
});
