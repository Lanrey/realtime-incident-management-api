import { PurchaseOrderService } from '../../services/purchaseOrder.service';
import { prisma } from '../../config/database';
import { rabbitmq } from '../../config/rabbitmq';
import { capacityManager } from '../../services/capacityManager.service';

jest.mock('../../config/rabbitmq', () => ({
  rabbitmq: {
    publish: jest.fn(),
  },
}));

jest.mock('../../services/capacityManager.service', () => ({
  capacityManager: {
    calculateOptimalOrderQuantity: jest.fn(),
  },
}));

describe('PurchaseOrderService', () => {
  let purchaseOrderService: PurchaseOrderService;

  beforeEach(() => {
    purchaseOrderService = new PurchaseOrderService();
    jest.clearAllMocks();
  });

  describe('createPurchaseOrder', () => {
    const mockProduct = {
      id: 'product-1',
      sku: 'SKU001',
      name: 'Test Product',
      unitPrice: 100,
      leadTimeDays: 7,
    };

    const mockOrder = {
      id: 'order-1',
      orderNumber: 'PO-20231201-123456',
      productId: 'product-1',
      supplierId: 'supplier-1',
      warehouseId: 'warehouse-1',
      quantityOrdered: 50,
      totalCost: 5000,
      status: 'PENDING',
      orderDate: new Date(),
      expectedArrivalDate: new Date(),
      notes: 'Test order',
      isAutoGenerated: false,
      product: mockProduct,
      supplier: { id: 'supplier-1', name: 'Test Supplier' },
      warehouse: { id: 'warehouse-1', name: 'Test Warehouse' },
    };

    it('should create purchase order successfully', async () => {
      (prisma.product.findUnique as jest.Mock).mockResolvedValue(mockProduct);
      (capacityManager.calculateOptimalOrderQuantity as jest.Mock).mockResolvedValue(50);
      (prisma.purchaseOrder.create as jest.Mock).mockResolvedValue(mockOrder);

      const result = await purchaseOrderService.createPurchaseOrder({
        productId: 'product-1',
        supplierId: 'supplier-1',
        warehouseId: 'warehouse-1',
        quantityOrdered: 50,
        notes: 'Test order',
      });

      expect(result).toEqual(mockOrder);
      expect(prisma.product.findUnique).toHaveBeenCalledWith({
        where: { id: 'product-1' },
      });
      expect(capacityManager.calculateOptimalOrderQuantity).toHaveBeenCalledWith(
        'product-1',
        'warehouse-1',
        50
      );
    });

    it('should throw error when product not found', async () => {
      (prisma.product.findUnique as jest.Mock).mockResolvedValue(null);

      await expect(
        purchaseOrderService.createPurchaseOrder({
          productId: 'non-existent',
          supplierId: 'supplier-1',
          warehouseId: 'warehouse-1',
          quantityOrdered: 50,
        })
      ).rejects.toThrow('Product not found');
    });

    it('should throw error when warehouse has insufficient capacity', async () => {
      (prisma.product.findUnique as jest.Mock).mockResolvedValue(mockProduct);
      (capacityManager.calculateOptimalOrderQuantity as jest.Mock).mockResolvedValue(0);

      await expect(
        purchaseOrderService.createPurchaseOrder({
          productId: 'product-1',
          supplierId: 'supplier-1',
          warehouseId: 'warehouse-1',
          quantityOrdered: 1000,
        })
      ).rejects.toThrow('Warehouse has insufficient capacity for this order');
    });

    it('should adjust order quantity based on capacity', async () => {
      (prisma.product.findUnique as jest.Mock).mockResolvedValue(mockProduct);
      (capacityManager.calculateOptimalOrderQuantity as jest.Mock).mockResolvedValue(30);
      (prisma.purchaseOrder.create as jest.Mock).mockResolvedValue({
        ...mockOrder,
        quantityOrdered: 30,
        totalCost: 3000,
      });

      const result = await purchaseOrderService.createPurchaseOrder({
        productId: 'product-1',
        supplierId: 'supplier-1',
        warehouseId: 'warehouse-1',
        quantityOrdered: 50,
      });

      expect(result.quantityOrdered).toBe(30);
      expect(result.totalCost).toBe(3000);
    });

    it('should calculate expected arrival date based on lead time', async () => {
      const now = new Date('2023-12-01');
      jest.useFakeTimers().setSystemTime(now);

      (prisma.product.findUnique as jest.Mock).mockResolvedValue(mockProduct);
      (capacityManager.calculateOptimalOrderQuantity as jest.Mock).mockResolvedValue(50);
      (prisma.purchaseOrder.create as jest.Mock).mockImplementation((params) => {
        return Promise.resolve({
          ...mockOrder,
          orderDate: params.data.orderDate,
          expectedArrivalDate: params.data.expectedArrivalDate,
        });
      });

      await purchaseOrderService.createPurchaseOrder({
        productId: 'product-1',
        supplierId: 'supplier-1',
        warehouseId: 'warehouse-1',
        quantityOrdered: 50,
      });

      expect(prisma.purchaseOrder.create).toHaveBeenCalledWith(
        expect.objectContaining({
          data: expect.objectContaining({
            orderDate: now,
            expectedArrivalDate: new Date('2023-12-08'), // 7 days later
          }),
        })
      );

      jest.useRealTimers();
    });

    it('should retry on order number collision', async () => {
      (prisma.product.findUnique as jest.Mock).mockResolvedValue(mockProduct);
      (capacityManager.calculateOptimalOrderQuantity as jest.Mock).mockResolvedValue(50);
      (prisma.purchaseOrder.create as jest.Mock)
        .mockRejectedValueOnce({ code: 'P2002' })
        .mockResolvedValueOnce(mockOrder);

      const result = await purchaseOrderService.createPurchaseOrder({
        productId: 'product-1',
        supplierId: 'supplier-1',
        warehouseId: 'warehouse-1',
        quantityOrdered: 50,
      });

      expect(result).toEqual(mockOrder);
      expect(prisma.purchaseOrder.create).toHaveBeenCalledTimes(2);
    });
  });

  describe('getPurchaseOrders', () => {
    it('should return paginated purchase orders', async () => {
      const mockOrders = [
        {
          id: 'order-1',
          orderNumber: 'PO-001',
          status: 'PENDING',
        },
      ];

      (prisma.purchaseOrder.findMany as jest.Mock).mockResolvedValue(mockOrders);
      (prisma.purchaseOrder.count as jest.Mock).mockResolvedValue(1);

      const result = await purchaseOrderService.getPurchaseOrders({
        page: 1,
        limit: 20,
        sortBy: 'createdAt',
        sortOrder: 'desc',
      });

      expect(result.orders).toEqual(mockOrders);
      expect(result.pagination).toEqual({
        page: 1,
        limit: 20,
        total: 1,
        totalPages: 1,
      });
    });

    it('should filter by status', async () => {
      (prisma.purchaseOrder.findMany as jest.Mock).mockResolvedValue([]);
      (prisma.purchaseOrder.count as jest.Mock).mockResolvedValue(0);

      await purchaseOrderService.getPurchaseOrders({
        page: 1,
        limit: 20,
        status: 'PENDING',
        sortBy: 'createdAt',
        sortOrder: 'desc',
      });

      expect(prisma.purchaseOrder.findMany).toHaveBeenCalledWith({
        where: { status: 'PENDING' },
        skip: 0,
        take: 20,
        orderBy: { createdAt: 'desc' },
        include: expect.any(Object),
      });
    });

    it('should filter by warehouse', async () => {
      (prisma.purchaseOrder.findMany as jest.Mock).mockResolvedValue([]);
      (prisma.purchaseOrder.count as jest.Mock).mockResolvedValue(0);

      await purchaseOrderService.getPurchaseOrders({
        page: 1,
        limit: 20,
        warehouseId: 'warehouse-1',
        sortBy: 'createdAt',
        sortOrder: 'desc',
      });

      expect(prisma.purchaseOrder.findMany).toHaveBeenCalledWith({
        where: { warehouseId: 'warehouse-1' },
        skip: 0,
        take: 20,
        orderBy: { createdAt: 'desc' },
        include: expect.any(Object),
      });
    });

    it('should filter by date range', async () => {
      (prisma.purchaseOrder.findMany as jest.Mock).mockResolvedValue([]);
      (prisma.purchaseOrder.count as jest.Mock).mockResolvedValue(0);

      await purchaseOrderService.getPurchaseOrders({
        page: 1,
        limit: 20,
        startDate: '2023-01-01',
        endDate: '2023-12-31',
        sortBy: 'createdAt',
        sortOrder: 'desc',
      });

      expect(prisma.purchaseOrder.findMany).toHaveBeenCalledWith({
        where: {
          orderDate: {
            gte: new Date('2023-01-01'),
            lte: new Date('2023-12-31'),
          },
        },
        skip: 0,
        take: 20,
        orderBy: { createdAt: 'desc' },
        include: expect.any(Object),
      });
    });

    it('should filter by isAutoGenerated flag', async () => {
      (prisma.purchaseOrder.findMany as jest.Mock).mockResolvedValue([]);
      (prisma.purchaseOrder.count as jest.Mock).mockResolvedValue(0);

      await purchaseOrderService.getPurchaseOrders({
        page: 1,
        limit: 20,
        isAutoGenerated: true,
        sortBy: 'createdAt',
        sortOrder: 'desc',
      });

      expect(prisma.purchaseOrder.findMany).toHaveBeenCalledWith({
        where: { isAutoGenerated: true },
        skip: 0,
        take: 20,
        orderBy: { createdAt: 'desc' },
        include: expect.any(Object),
      });
    });
  });

  describe('getPurchaseOrderById', () => {
    it('should return purchase order by ID', async () => {
      const mockOrder = {
        id: 'order-1',
        orderNumber: 'PO-001',
        status: 'PENDING',
      };

      (prisma.purchaseOrder.findUnique as jest.Mock).mockResolvedValue(mockOrder);

      const result = await purchaseOrderService.getPurchaseOrderById('order-1');

      expect(result).toEqual(mockOrder);
      expect(prisma.purchaseOrder.findUnique).toHaveBeenCalledWith({
        where: { id: 'order-1' },
        include: expect.any(Object),
      });
    });

    it('should return null for non-existent order', async () => {
      (prisma.purchaseOrder.findUnique as jest.Mock).mockResolvedValue(null);

      const result = await purchaseOrderService.getPurchaseOrderById('non-existent');

      expect(result).toBeNull();
    });
  });

  describe('updatePurchaseOrder', () => {
    it('should update purchase order', async () => {
      const mockUpdatedOrder = {
        id: 'order-1',
        status: 'IN_TRANSIT',
      };

      (prisma.purchaseOrder.update as jest.Mock).mockResolvedValue(mockUpdatedOrder);

      const result = await purchaseOrderService.updatePurchaseOrder('order-1', {
        status: 'IN_TRANSIT',
      });

      expect(result).toEqual(mockUpdatedOrder);
      expect(prisma.purchaseOrder.update).toHaveBeenCalledWith({
        where: { id: 'order-1' },
        data: { status: 'IN_TRANSIT' },
        include: expect.any(Object),
      });
    });
  });

  describe('markOrderAsArrived', () => {
    it('should publish order arrival event to queue', async () => {
      (rabbitmq.publish as jest.Mock).mockResolvedValue(undefined);

      const result = await purchaseOrderService.markOrderAsArrived('order-1');

      expect(result).toEqual({ message: 'Order arrival is being processed' });
      expect(rabbitmq.publish).toHaveBeenCalledWith(
        'order.arrival',
        { purchaseOrderId: 'order-1' },
        8
      );
    });
  });

  describe('cancelPurchaseOrder', () => {
    it('should cancel pending purchase order', async () => {
      const mockOrder = {
        id: 'order-1',
        status: 'PENDING',
      };

      (prisma.purchaseOrder.findUnique as jest.Mock).mockResolvedValue(mockOrder);
      (prisma.purchaseOrder.update as jest.Mock).mockResolvedValue({
        ...mockOrder,
        status: 'CANCELLED',
      });

      await purchaseOrderService.cancelPurchaseOrder('order-1');

      expect(prisma.purchaseOrder.update).toHaveBeenCalledWith({
        where: { id: 'order-1' },
        data: { status: 'CANCELLED' },
      });
    });

    it('should throw error when order not found', async () => {
      (prisma.purchaseOrder.findUnique as jest.Mock).mockResolvedValue(null);

      await expect(purchaseOrderService.cancelPurchaseOrder('non-existent')).rejects.toThrow(
        'Purchase order not found'
      );
    });

    it('should throw error when trying to cancel arrived order', async () => {
      const mockOrder = {
        id: 'order-1',
        status: 'ARRIVED',
      };

      (prisma.purchaseOrder.findUnique as jest.Mock).mockResolvedValue(mockOrder);

      await expect(purchaseOrderService.cancelPurchaseOrder('order-1')).rejects.toThrow(
        'Cannot cancel an order that has already arrived'
      );

      expect(prisma.purchaseOrder.update).not.toHaveBeenCalled();
    });
  });

  describe('getPendingOrders', () => {
    it('should return pending and in-transit orders', async () => {
      const mockOrders = [
        { id: 'order-1', status: 'PENDING' },
        { id: 'order-2', status: 'IN_TRANSIT' },
      ];

      (prisma.purchaseOrder.findMany as jest.Mock).mockResolvedValue(mockOrders);

      const result = await purchaseOrderService.getPendingOrders();

      expect(result).toEqual(mockOrders);
      expect(prisma.purchaseOrder.findMany).toHaveBeenCalledWith({
        where: {
          status: {
            in: ['PENDING', 'IN_TRANSIT'],
          },
        },
        orderBy: { expectedArrivalDate: 'asc' },
        include: expect.any(Object),
      });
    });

    it('should filter pending orders by warehouse', async () => {
      (prisma.purchaseOrder.findMany as jest.Mock).mockResolvedValue([]);

      await purchaseOrderService.getPendingOrders('warehouse-1');

      expect(prisma.purchaseOrder.findMany).toHaveBeenCalledWith({
        where: {
          status: {
            in: ['PENDING', 'IN_TRANSIT'],
          },
          warehouseId: 'warehouse-1',
        },
        orderBy: { expectedArrivalDate: 'asc' },
        include: expect.any(Object),
      });
    });
  });

  describe('getOrderStatistics', () => {
    it('should return comprehensive order statistics', async () => {
      (prisma.purchaseOrder.count as jest.Mock)
        .mockResolvedValueOnce(100) // total
        .mockResolvedValueOnce(30) // pending
        .mockResolvedValueOnce(20) // in transit
        .mockResolvedValueOnce(45); // arrived

      (prisma.purchaseOrder.aggregate as jest.Mock).mockResolvedValue({
        _sum: { totalCost: 50000 },
      });

      const result = await purchaseOrderService.getOrderStatistics();

      expect(result).toEqual({
        totalOrders: 100,
        pendingOrders: 30,
        inTransitOrders: 20,
        arrivedOrders: 45,
        totalValue: 50000,
      });
    });

    it('should handle null total cost', async () => {
      (prisma.purchaseOrder.count as jest.Mock).mockResolvedValue(0);
      (prisma.purchaseOrder.aggregate as jest.Mock).mockResolvedValue({
        _sum: { totalCost: null },
      });

      const result = await purchaseOrderService.getOrderStatistics();

      expect(result.totalValue).toBe(0);
    });

    it('should filter statistics by warehouse', async () => {
      (prisma.purchaseOrder.count as jest.Mock).mockResolvedValue(0);
      (prisma.purchaseOrder.aggregate as jest.Mock).mockResolvedValue({
        _sum: { totalCost: null },
      });

      await purchaseOrderService.getOrderStatistics('warehouse-1');

      expect(prisma.purchaseOrder.count).toHaveBeenCalledWith({
        where: { warehouseId: 'warehouse-1' },
      });
    });
  });
});
